"""Autonomous Recovery Engine with Bounded Retries, Quarantine, Cooldown, and Governance."""
import time
from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum
from pathlib import Path
from typing import Any, Callable, Dict, List, Optional, Tuple
import pandas as pd
from config.settings import get_settings
from src.database import (
    get_active_model,
    get_connection,
    get_model_history,
    log_recovery_action,
    log_system_event,
)
from src.model_registry import ModelRegistryManager


class RecoveryTrigger(str, Enum):
    TEMPORARY_PROCESSING_FAILURE = "TEMPORARY_PROCESSING_FAILURE"
    INVALID_INCOMING_DATA = "INVALID_INCOMING_DATA"
    DATA_DRIFT_DETECTED = "DATA_DRIFT_DETECTED"
    CANDIDATE_MODEL_DEGRADATION = "CANDIDATE_MODEL_DEGRADATION"
    DEPLOYMENT_FAILURE = "DEPLOYMENT_FAILURE"


class RecoveryActionType(str, Enum):
    RETRY_WITH_BACKOFF = "RETRY_WITH_BACKOFF"
    QUARANTINE_RECORDS = "QUARANTINE_RECORDS"
    TRIGGER_RETRAINING = "TRIGGER_RETRAINING"
    REJECT_CANDIDATE_MODEL = "REJECT_CANDIDATE_MODEL"
    ROLLBACK_MODEL = "ROLLBACK_MODEL"
    ALERT_AND_HALT = "ALERT_AND_HALT"


@dataclass
class RecoveryDecision:
    """Action plan generated by the rule-based decision engine."""
    trigger: RecoveryTrigger
    recommended_action: RecoveryActionType
    can_auto_execute: bool
    explanation: str
    context: Dict[str, Any] = field(default_factory=dict)


@dataclass
class RecoveryExecutionResult:
    """Outcome of an attempted or completed recovery action."""
    action_id: str
    trigger: str
    action_type: str
    status: str  # 'SUCCESS', 'FAILED', 'SKIPPED', 'COOLED_DOWN'
    attempts: int
    outcome_summary: str
    error_details: Optional[str] = None
    verification_passed: bool = True
    verification_details: Optional[str] = None


class RecoveryEngine:
    """
    Autonomous decision engine executing safe, auditable recovery workflows.
    Protects against infinite recovery loops via cooldown periods and bounded retries.
    """

    def __init__(self):
        self.settings = get_settings()
        self.registry = ModelRegistryManager()

    def check_cooldown(self, action_type: str) -> Tuple[bool, int]:
        """
        Check if an action is blocked by the recovery cooldown period.
        Returns: (is_cooling_down: bool, remaining_seconds: int)
        """
        cooldown_sec = self.settings.recovery_cooldown_seconds
        with get_connection(self.settings.database_path) as conn:
            cursor = conn.cursor()
            cursor.execute("""
                SELECT created_at FROM recovery_actions
                WHERE action_type = ? AND status = 'SUCCESS'
                ORDER BY created_at DESC
                LIMIT 1
            """, (action_type,))
            row = cursor.fetchone()
            if not row:
                return False, 0
            
            last_time_str = row["created_at"]
            try:
                # Parse SQLite ISO timestamp
                last_time = datetime.fromisoformat(last_time_str)
                # Ensure UTC
                if last_time.tzinfo is None:
                    last_time = last_time.replace(tzinfo=timezone.utc)
                now_utc = datetime.now(timezone.utc)
                elapsed = (now_utc - last_time).total_seconds()
                if elapsed < cooldown_sec:
                    return True, int(cooldown_sec - elapsed)
            except Exception:
                return False, 0

        return False, 0

    def evaluate_pipeline_situation(
        self,
        has_processing_error: bool = False,
        error_message: Optional[str] = None,
        quarantined_count: int = 0,
        drift_status: str = "HEALTHY",
        candidate_degraded: bool = False,
        candidate_version: Optional[str] = None,
        deployment_failed: bool = False,
    ) -> List[RecoveryDecision]:
        """
        Analyze current pipeline diagnostics and determine appropriate recovery decisions.
        """
        decisions: List[RecoveryDecision] = []

        # 1. Temporary Processing Failure
        if has_processing_error:
            decisions.append(RecoveryDecision(
                trigger=RecoveryTrigger.TEMPORARY_PROCESSING_FAILURE,
                recommended_action=RecoveryActionType.RETRY_WITH_BACKOFF,
                can_auto_execute=True,
                explanation=(
                    f"Temporary processing failure detected: '{error_message}'. "
                    f"Initiating bounded retry with exponential backoff (Max {self.settings.max_retry_attempts} attempts)."
                ),
                context={"error": error_message},
            ))

        # 2. Invalid Incoming Data (Quarantine)
        if quarantined_count > 0:
            decisions.append(RecoveryDecision(
                trigger=RecoveryTrigger.INVALID_INCOMING_DATA,
                recommended_action=RecoveryActionType.QUARANTINE_RECORDS,
                can_auto_execute=True,
                explanation=(
                    f"Detected {quarantined_count} corrupted or out-of-range records. "
                    "Isolating invalid rows into secure quarantine storage; continuing valid records."
                ),
                context={"quarantined_count": quarantined_count},
            ))

        # 3. Data Drift Detected
        if drift_status in ["WARNING", "CRITICAL"]:
            decisions.append(RecoveryDecision(
                trigger=RecoveryTrigger.DATA_DRIFT_DETECTED,
                recommended_action=RecoveryActionType.TRIGGER_RETRAINING,
                can_auto_execute=(self.settings.auto_recovery_mode == "automatic"),
                explanation=(
                    f"Statistical data drift detected (Severity: {drift_status}). "
                    "Recommend triggering candidate retraining with fresh labeled data if validation criteria are met."
                ),
                context={"drift_status": drift_status},
            ))

        # 4. Candidate Model Degradation
        if candidate_degraded:
            decisions.append(RecoveryDecision(
                trigger=RecoveryTrigger.CANDIDATE_MODEL_DEGRADATION,
                recommended_action=RecoveryActionType.REJECT_CANDIDATE_MODEL,
                can_auto_execute=True,
                explanation=(
                    f"Candidate model {candidate_version or ''} failed validation acceptance criteria. "
                    "Preserving currently active model; recording audit rejection log."
                ),
                context={"version": candidate_version},
            ))

        # 5. Deployment / Runtime Model Failure
        if deployment_failed:
            decisions.append(RecoveryDecision(
                trigger=RecoveryTrigger.DEPLOYMENT_FAILURE,
                recommended_action=RecoveryActionType.ROLLBACK_MODEL,
                can_auto_execute=True,
                explanation=(
                    "Active model failed inference or integrity check. "
                    "Initiating immediate rollback to the last validated healthy model version."
                ),
                context={},
            ))

        return decisions

    def execute_bounded_retry(
        self,
        operation: Callable[[], Any],
        operation_name: str = "Operation",
        max_attempts: Optional[int] = None,
        backoff_sec: Optional[float] = None,
        run_id: Optional[str] = None,
    ) -> Tuple[bool, Any, RecoveryExecutionResult]:
        """
        Execute an operation with bounded retries and exponential backoff.
        """
        max_attempts = max_attempts or self.settings.max_retry_attempts
        backoff = backoff_sec or self.settings.retry_backoff_seconds
        last_error = None

        for attempt in range(1, max_attempts + 1):
            try:
                result = operation()
                summary = f"{operation_name} succeeded on attempt {attempt}/{max_attempts}."
                action_id = log_recovery_action(
                    trigger_event=RecoveryTrigger.TEMPORARY_PROCESSING_FAILURE.value,
                    action_type=RecoveryActionType.RETRY_WITH_BACKOFF.value,
                    status="SUCCESS",
                    outcome_summary=summary,
                    run_id=run_id,
                    attempts=attempt,
                )
                log_system_event(
                    event_type="RETRY_RECOVERY_SUCCESS",
                    severity="INFO",
                    component="RECOVERY_ENGINE",
                    description=summary,
                    action_taken=f"Retry attempt {attempt}",
                    outcome="SUCCESS",
                )
                return True, result, RecoveryExecutionResult(
                    action_id=action_id,
                    trigger=RecoveryTrigger.TEMPORARY_PROCESSING_FAILURE.value,
                    action_type=RecoveryActionType.RETRY_WITH_BACKOFF.value,
                    status="SUCCESS",
                    attempts=attempt,
                    outcome_summary=summary,
                )
            except Exception as e:
                last_error = str(e)
                if attempt < max_attempts:
                    sleep_time = backoff * (2 ** (attempt - 1))
                    time.sleep(sleep_time)

        # Exhausted retries
        fail_summary = f"{operation_name} failed after {max_attempts} retry attempts. Final error: {last_error}"
        action_id = log_recovery_action(
            trigger_event=RecoveryTrigger.TEMPORARY_PROCESSING_FAILURE.value,
            action_type=RecoveryActionType.RETRY_WITH_BACKOFF.value,
            status="FAILED",
            outcome_summary=fail_summary,
            run_id=run_id,
            attempts=max_attempts,
            error_details=last_error,
        )
        log_system_event(
            event_type="RETRY_EXHAUSTED",
            severity="CRITICAL",
            component="RECOVERY_ENGINE",
            description=fail_summary,
            action_taken="BOUNDED_RETRY_EXHAUSTED",
            outcome="FAILED",
            error_details=last_error,
        )
        return False, None, RecoveryExecutionResult(
            action_id=action_id,
            trigger=RecoveryTrigger.TEMPORARY_PROCESSING_FAILURE.value,
            action_type=RecoveryActionType.RETRY_WITH_BACKOFF.value,
            status="FAILED",
            attempts=max_attempts,
            outcome_summary=fail_summary,
            error_details=last_error,
        )

    def execute_quarantine(
        self,
        quarantined_df: pd.DataFrame,
        quarantine_file_path: Optional[str],
        run_id: Optional[str] = None,
    ) -> RecoveryExecutionResult:
        """Execute quarantine isolation with post-action disk verification."""
        count = len(quarantined_df)
        
        # Post-action verification
        verif_passed = True
        verif_details = ""
        if quarantine_file_path:
            q_file = Path(quarantine_file_path)
            if not q_file.exists() and not quarantined_df.empty:
                q_file.parent.mkdir(parents=True, exist_ok=True)
                quarantined_df.to_csv(q_file, index=False)
            if not q_file.exists() or q_file.stat().st_size == 0:
                verif_passed = False
                verif_details = "Quarantine verification failed: target file missing or empty."
            else:
                verif_passed = True
                verif_details = f"Verified {count} quarantined records written to storage ({q_file.name})."
        else:
            verif_passed = True
            verif_details = "Verified zero records required quarantine."

        status_str = "SUCCESS" if verif_passed else "FAILED"
        summary = (
            f"Successfully isolated {count} invalid records into quarantine storage ({quarantine_file_path}). "
            "Downstream processing continued for valid subset."
        )
        action_id = log_recovery_action(
            trigger_event=RecoveryTrigger.INVALID_INCOMING_DATA.value,
            action_type=RecoveryActionType.QUARANTINE_RECORDS.value,
            status=status_str,
            outcome_summary=summary,
            run_id=run_id,
            attempts=1,
            error_details=None if verif_passed else verif_details,
        )
        log_system_event(
            event_type="DATA_QUARANTINE",
            severity="WARNING" if verif_passed else "ERROR",
            component="RECOVERY_ENGINE",
            description=summary,
            action_taken="ISOLATE_INVALID_RECORDS",
            outcome=status_str,
            error_details=None if verif_passed else verif_details,
        )
        return RecoveryExecutionResult(
            action_id=action_id,
            trigger=RecoveryTrigger.INVALID_INCOMING_DATA.value,
            action_type=RecoveryActionType.QUARANTINE_RECORDS.value,
            status=status_str,
            attempts=1,
            outcome_summary=summary,
            error_details=None if verif_passed else verif_details,
            verification_passed=verif_passed,
            verification_details=verif_details,
        )

    def execute_drift_retraining(
        self,
        training_df: pd.DataFrame,
        force: bool = False,
        run_id: Optional[str] = None,
    ) -> RecoveryExecutionResult:
        """
        Execute automated retraining triggered by drift, respecting cooldown and verifying outcome.
        """
        action_type = RecoveryActionType.TRIGGER_RETRAINING.value
        
        # Check cooldown
        if not force:
            cooling, remaining = self.check_cooldown(action_type)
            if cooling:
                msg = f"Retraining blocked by cooldown. Please wait {remaining} seconds to prevent retraining thrashing."
                action_id = log_recovery_action(
                    trigger_event=RecoveryTrigger.DATA_DRIFT_DETECTED.value,
                    action_type=action_type,
                    status="SKIPPED",
                    outcome_summary=msg,
                    run_id=run_id,
                )
                return RecoveryExecutionResult(
                    action_id=action_id,
                    trigger=RecoveryTrigger.DATA_DRIFT_DETECTED.value,
                    action_type=action_type,
                    status="COOLED_DOWN",
                    attempts=1,
                    outcome_summary=msg,
                    verification_passed=True,
                    verification_details="Cooldown gate successfully prevented rapid repeated retraining loop.",
                )

        promoted, msg, meta = self.registry.validate_and_register_candidate(
            df=training_df,
            algorithm="RandomForest",
            degrade_intentionally=False,
            trigger_source="DRIFT_AUTO_RECOVERY",
        )

        # Post-action verification
        verif_passed = False
        verif_details = ""
        if promoted:
            try:
                # 1. Verify artifact exists and is loadable
                art_path = meta.get("artifact_path")
                if art_path and Path(art_path).exists():
                    loaded = self.registry.load_model_artifact(art_path)
                    # 2. Sanity test inference on 5 samples
                    sample_x = training_df.head(5)
                    test_preds = loaded["model"].predict(loaded["preprocessor"].transform(sample_x)[0])
                    # 3. Verify active model in DB matches promoted version
                    active_now = get_active_model(self.settings.database_path)
                    if active_now and active_now["model_version"] == meta["version"] and len(test_preds) == 5:
                        verif_passed = True
                        verif_details = f"Post-retraining verification passed: {meta['version']} active and inference sanity verified."
                    else:
                        verif_details = "Verification failed: Active model version mismatch or inference test failed."
                else:
                    verif_details = "Verification failed: Trained model artifact not found on disk."
            except Exception as e:
                verif_passed = False
                verif_details = f"Verification failed with exception: {str(e)}"
        else:
            # Candidate was rejected by validation gate
            verif_passed = True
            verif_details = f"Rejection policy verified: Candidate rejected ({meta.get('rejection_reason')}); active model preserved."

        status_str = "SUCCESS" if (promoted and verif_passed) or (not promoted and verif_passed) else "FAILED"
        action_id = log_recovery_action(
            trigger_event=RecoveryTrigger.DATA_DRIFT_DETECTED.value,
            action_type=action_type,
            status=status_str,
            outcome_summary=msg,
            run_id=run_id,
            attempts=1,
            error_details=meta.get("rejection_reason") or (None if verif_passed else verif_details),
        )

        return RecoveryExecutionResult(
            action_id=action_id,
            trigger=RecoveryTrigger.DATA_DRIFT_DETECTED.value,
            action_type=action_type,
            status=status_str,
            attempts=1,
            outcome_summary=msg,
            error_details=meta.get("rejection_reason"),
            verification_passed=verif_passed,
            verification_details=verif_details,
        )

    def execute_rollback(
        self,
        target_version: Optional[str] = None,
        run_id: Optional[str] = None,
    ) -> RecoveryExecutionResult:
        """
        Execute rollback to a previously validated model version with post-action verification.
        """
        history = get_model_history(self.settings.database_path)
        if not target_version:
            healthy_models = [m for m in history if m["status"] in ["archived", "active"]]
            if len(healthy_models) < 2 and not healthy_models:
                fail_msg = "Rollback aborted: No validated previous model exists in registry."
                action_id = log_recovery_action(
                    trigger_event=RecoveryTrigger.DEPLOYMENT_FAILURE.value,
                    action_type=RecoveryActionType.ROLLBACK_MODEL.value,
                    status="FAILED",
                    outcome_summary=fail_msg,
                    run_id=run_id,
                    db_path=self.settings.database_path,
                )
                return RecoveryExecutionResult(
                    action_id=action_id,
                    trigger=RecoveryTrigger.DEPLOYMENT_FAILURE.value,
                    action_type=RecoveryActionType.ROLLBACK_MODEL.value,
                    status="FAILED",
                    attempts=1,
                    outcome_summary=fail_msg,
                    error_details="No fallback model found.",
                    verification_passed=False,
                    verification_details="No historical model artifact available in database.",
                )
            target_version = (
                healthy_models[1]["model_version"]
                if len(healthy_models) > 1 and healthy_models[0]["status"] == "active"
                else healthy_models[0]["model_version"]
            )

        success, msg = self.registry.rollback_to_version(target_version)
        
        # Post-action verification
        verif_passed = False
        verif_details = ""
        if success:
            try:
                active_now = get_active_model(self.settings.database_path)
                if active_now and active_now["model_version"] == target_version:
                    # Sanity check load artifact
                    art = self.registry.load_model_artifact(active_now["artifact_path"])
                    if art and "model" in art:
                        verif_passed = True
                        verif_details = f"Rollback verified: Model {target_version} successfully restored to active state and artifact verified."
                    else:
                        verif_details = "Rollback verification failed: Model artifact payload incomplete."
                else:
                    verif_details = f"Rollback verification failed: Registry active version does not match target {target_version}."
            except Exception as e:
                verif_passed = False
                verif_details = f"Rollback verification failed: {str(e)}"
        else:
            verif_details = f"Rollback aborted: {msg}"

        status_str = "SUCCESS" if (success and verif_passed) else "FAILED"

        action_id = log_recovery_action(
            trigger_event=RecoveryTrigger.DEPLOYMENT_FAILURE.value,
            action_type=RecoveryActionType.ROLLBACK_MODEL.value,
            status=status_str,
            outcome_summary=msg,
            run_id=run_id,
            attempts=1,
            db_path=self.settings.database_path,
            error_details=None if verif_passed else verif_details,
        )

        return RecoveryExecutionResult(
            action_id=action_id,
            trigger=RecoveryTrigger.DEPLOYMENT_FAILURE.value,
            action_type=RecoveryActionType.ROLLBACK_MODEL.value,
            status=status_str,
            attempts=1,
            outcome_summary=msg,
            error_details=None if verif_passed else verif_details,
            verification_passed=verif_passed,
            verification_details=verif_details,
        )

    def execute_alert_and_halt(
        self,
        reason: str = "",
        run_id: Optional[str] = None,
        incident_description: Optional[str] = None,
    ) -> RecoveryExecutionResult:
        """Halt pipeline processing and log an immutable critical alert."""
        final_reason = incident_description or reason or "Critical unrecoverable anomaly"
        summary = f"Pipeline safety halt triggered: {final_reason}"
        action_id = log_recovery_action(
            trigger_event="CRITICAL_PIPELINE_FAULT",
            action_type=RecoveryActionType.ALERT_AND_HALT.value,
            status="HALTED",
            outcome_summary=summary,
            run_id=run_id,
            attempts=1,
            error_details=final_reason,
            db_path=self.settings.database_path,
        )
        log_system_event(
            event_type="PIPELINE_HALTED_ALERT",
            severity="CRITICAL",
            component="RECOVERY_ENGINE",
            description=summary,
            action_taken="ALERT_AND_HALT",
            outcome="HALTED",
            error_details=final_reason,
            db_path=self.settings.database_path,
        )
        return RecoveryExecutionResult(
            action_id=action_id,
            trigger="CRITICAL_PIPELINE_FAULT",
            action_type=RecoveryActionType.ALERT_AND_HALT.value,
            status="HALTED",
            attempts=1,
            outcome_summary=summary,
            error_details=final_reason,
            verification_passed=True,
            verification_details="Pipeline halted safely and audit alert logged.",
        )
